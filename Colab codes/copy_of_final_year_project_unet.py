from sklearn.model_selection import KFold
from tensorflow.keras.models import Model
import numpy as np

kfold = KFold(n_splits=5, shuffle=True, random_state=42)
cv_scores = []

for fold, (train_idx, val_idx) in enumerate(kfold.split(X, y_categorical)):
    print(f"\n===== Fold {fold+1} =====")

    X_train_cv, X_val_cv = X[train_idx], X[val_idx]
    y_train_cv, y_val_cv = y_categorical[train_idx], y_categorical[val_idx]

    # Rebuild model for each fold
    inputs = Input((IMG_HEIGHT, IMG_WIDTH, CHANNELS))

    c1 = Conv2D(32, (3,3), activation='relu', padding='same')(inputs)
    p1 = MaxPooling2D((2,2))(c1)

    c2 = Conv2D(64, (3,3), activation='relu', padding='same')(p1)
    p2 = MaxPooling2D((2,2))(c2)

    c3 = Conv2D(128, (3,3), activation='relu', padding='same')(p2)
    p3 = MaxPooling2D((2,2))(c3)

    bottleneck = Conv2D(256, (3,3), activation='relu', padding='same')(p3)

    x = Flatten()(bottleneck)
    x = Dense(128, activation='relu')(x)
    x = Dropout(0.5)(x)
    outputs = Dense(y_train_cv.shape[1], activation='softmax')(x)

    model = Model(inputs, outputs)

    model.compile(optimizer='adam', loss='categorical_crossentropy', metrics=['accuracy'])

    model.fit(X_train_cv, y_train_cv, epochs=10, batch_size=16, verbose=0)

    loss, acc = model.evaluate(X_val_cv, y_val_cv, verbose=0)
    print(f"Fold Accuracy: {acc*100:.2f}%")
    cv_scores.append(acc)

print("\nMean CV Accuracy:", np.mean(cv_scores)*100)
print("Std Dev:", np.std(cv_scores)*100)